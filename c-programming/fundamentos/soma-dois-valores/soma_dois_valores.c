#include <stdio.h> // Biblioteca que permite usar o printf()

int main() {

    // Declaração das variáveis inteiras
    int valor1;
    int valor2;
    int soma;

    // Atribuindo o valor 20 para a variável valor1
    valor1 = 20;

    // Atribuindo o valor 20 para a variável valor2
    valor2 = 20;

    // Somando valor1 + valor2 e guardando o resultado em soma
    soma = valor1 + valor2;

    // Exibe o resultado da soma na tela
    // %d representa um número inteiro
    printf("Resultado da soma eh  %d", soma);

    // Indica que o programa terminou corretamente
    return 0;
}
